import { describe, it, expect } from "vitest";
import {
  buildAuthCallAllocateIntoMsg,
  buildAuthCallSetupMsg,
  buildCommitChangeSet,
} from "./vault-payloads";

// Golden vectors: the EXACT canonical serialization emitted by the contract's serde, pinned
// in contract/crates/vault/tests/golden_vectors.rs. If either side drifts, one of these
// fails — that is the anti-orphan guarantee for the money-critical bodies. Keep the inputs
// here identical to sample_auth_call_msg() / sample_change_set() on the Rust side.

const AUTH_CALL_MSG_GOLDEN =
  '{"deadline":1000,"nonce":[7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7],"op":{"setup":{"login_wallet":{"chain":"near","address":"alice.near"},"portfolio_name":"Golden Portfolio","composition":[{"token_id":"nep141:usdc.near","target_bps":10000,"tolerance_bps":500}],"allocations":[["nep141:usdc.near","1000000"]]}}}';

const CHANGE_SET_GOLDEN =
  '{"portfolio_id":"pf-golden-1","target_changes":[],"token_additions":[],"token_removals":[],"unallocations":[["nep141:usdc.near","1000000"]]}';

// The composition-carrying shape (008.plan Phase 2). Generated the same way as the vectors
// above — `serde_json::to_string` on a PortfolioChangeSet built in the contract's own test
// harness — rather than reasoned out from the struct: the tuple-as-array encoding of
// `Vec<(TokenId, u16, u16)>` is exactly the kind of assumption that orphans funds.
const COMPOSITION_CHANGE_SET_GOLDEN =
  '{"portfolio_id":"pf-golden-1","target_changes":[["nep141:usdc.near",6000,500]],"token_additions":[["nep141:wnear.near",0,1000]],"token_removals":["nep141:dai.near"],"unallocations":[["nep141:dai.near","250"]]}';

const ADD_WITH_TARGET_CHANGE_SET_GOLDEN =
  '{"portfolio_id":"p_00000000002a","target_changes":[["nep141:usdc.near",6000,500]],"token_additions":[["nep141:eth.omft.near",4000,300]],"token_removals":[],"unallocations":[]}';

// v2 (017-9c): a signed delete and a rename-only change set. Pinned by
// `golden_change_set_delete` / `golden_change_set_rename_only` in the final contract's
// golden_vectors.rs. Both optional fields are absent unless set, and come after `unallocations`.
const DELETE_CHANGE_SET_GOLDEN =
  '{"portfolio_id":"p_00000000002a","target_changes":[],"token_additions":[],"token_removals":[],"unallocations":[],"delete":true}';

const RENAME_CHANGE_SET_GOLDEN =
  '{"portfolio_id":"p_00000000002a","target_changes":[],"token_additions":[],"token_removals":[],"unallocations":[],"name":"Long term"}';

// AllocateOp::AllocateInto (D-321). Generated by `serde_json::to_string` on an `AuthCallMsg`
// built against the source of the DEPLOYED staging wasm (tag `vault-staging-v1`), not the
// monorepo HEAD — and cross-checked the other way too: the contract parsed the FE's output
// back into the type and re-serialised it byte for byte (013.plan B0). The shape is the same
// in the final contract (`allocate.rs` AllocateOp::AllocateInto).
const ALLOCATE_INTO_GOLDEN =
  '{"deadline":1000,"nonce":[7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7],"op":{"allocate_into":{"portfolio_id":"p_000000000001","target_changes":[],"token_additions":[["nep141:wrap.near",0,1000]],"token_removals":[],"allocations":[["nep141:usdc.near","1000000"],["nep141:wrap.near","250"]]}}}';

const ALLOCATE_INTO_FULL_GOLDEN =
  '{"deadline":1000,"nonce":[7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7],"op":{"allocate_into":{"portfolio_id":"p_000000000001","target_changes":[["nep141:usdc.near",6000,500]],"token_additions":[["nep141:wrap.near",0,1000]],"token_removals":["nep141:dai.near"],"allocations":[["nep141:usdc.near","1000000"]]}}}';

describe("vault payload builders — byte-identity vs Rust golden vectors", () => {
  it("buildAuthCallSetupMsg matches the contract's AuthCallMsg serialization", () => {
    const msg = buildAuthCallSetupMsg({
      deadline: 1000,
      nonce: Array(32).fill(7),
      chain: "near",
      address: "alice.near",
      portfolioName: "Golden Portfolio",
      composition: [{ tokenId: "nep141:usdc.near", targetBps: 10000, toleranceBps: 500 }],
      allocations: [{ tokenId: "nep141:usdc.near", amount: "1000000" }],
    });
    expect(msg).toBe(AUTH_CALL_MSG_GOLDEN);
  });

  it("buildCommitChangeSet matches the contract's PortfolioChangeSet serialization", () => {
    const changeSet = buildCommitChangeSet({
      portfolioId: "pf-golden-1",
      unallocations: [{ tokenId: "nep141:usdc.near", amount: "1000000" }],
    });
    expect(JSON.stringify(changeSet)).toBe(CHANGE_SET_GOLDEN);
  });

  it("buildCommitChangeSet matches it with composition edits too", () => {
    const changeSet = buildCommitChangeSet({
      portfolioId: "pf-golden-1",
      targetChanges: [{ tokenId: "nep141:usdc.near", targetBps: 6000, toleranceBps: 500 }],
      tokenAdditions: [{ tokenId: "nep141:wnear.near", targetBps: 0, toleranceBps: 1000 }],
      tokenRemovals: ["nep141:dai.near"],
      unallocations: [{ tokenId: "nep141:dai.near", amount: "250" }],
    });
    expect(JSON.stringify(changeSet)).toBe(COMPOSITION_CHANGE_SET_GOLDEN);
  });

  // v2 (017-9a, FE #6): an addition carries its target in the same commit. Pinned by
  // `golden_change_set_addition_with_target` in the final contract's golden_vectors.rs (1.9).
  it("buildCommitChangeSet matches the v2 addition-with-target vector", () => {
    const changeSet = buildCommitChangeSet({
      portfolioId: "p_00000000002a",
      targetChanges: [{ tokenId: "nep141:usdc.near", targetBps: 6000, toleranceBps: 500 }],
      tokenAdditions: [{ tokenId: "nep141:eth.omft.near", targetBps: 4000, toleranceBps: 300 }],
    });
    expect(JSON.stringify(changeSet)).toBe(ADD_WITH_TARGET_CHANGE_SET_GOLDEN);
  });

  it("buildCommitChangeSet matches the v2 signed-delete vector", () => {
    const changeSet = buildCommitChangeSet({ portfolioId: "p_00000000002a", delete: true });
    expect(JSON.stringify(changeSet)).toBe(DELETE_CHANGE_SET_GOLDEN);
  });

  it("buildCommitChangeSet matches the v2 rename-only vector", () => {
    const changeSet = buildCommitChangeSet({ portfolioId: "p_00000000002a", name: "Long term" });
    expect(JSON.stringify(changeSet)).toBe(RENAME_CHANGE_SET_GOLDEN);
  });

  it("omits name and delete when unset or false (the v1 pre-image stays byte-identical)", () => {
    const changeSet = buildCommitChangeSet({ portfolioId: "p_00000000002a", delete: false });
    expect(Object.keys(changeSet)).not.toContain("delete");
    expect(Object.keys(changeSet)).not.toContain("name");
  });

  it("buildAuthCallAllocateIntoMsg matches the contract's AllocateInto serialization", () => {
    const msg = buildAuthCallAllocateIntoMsg({
      deadline: 1000,
      nonce: Array(32).fill(7),
      portfolioId: "p_000000000001",
      tokenAdditions: [{ tokenId: "nep141:wrap.near", targetBps: 0, toleranceBps: 1000 }],
      allocations: [
        { tokenId: "nep141:usdc.near", amount: "1000000" },
        { tokenId: "nep141:wrap.near", amount: "250" },
      ],
    });
    expect(msg).toBe(ALLOCATE_INTO_GOLDEN);
  });

  it("buildAuthCallAllocateIntoMsg matches it with every composition list populated", () => {
    const msg = buildAuthCallAllocateIntoMsg({
      deadline: 1000,
      nonce: Array(32).fill(7),
      portfolioId: "p_000000000001",
      targetChanges: [{ tokenId: "nep141:usdc.near", targetBps: 6000, toleranceBps: 500 }],
      tokenAdditions: [{ tokenId: "nep141:wrap.near", targetBps: 0, toleranceBps: 1000 }],
      tokenRemovals: ["nep141:dai.near"],
      allocations: [{ tokenId: "nep141:usdc.near", amount: "1000000" }],
    });
    expect(msg).toBe(ALLOCATE_INTO_FULL_GOLDEN);
  });

  it("emits all four lists even when empty, in the Rust declaration order", () => {
    // serde needs the fields present, and the signed bytes are order-sensitive: a change
    // set that omits an empty list is a different pre-image.
    const changeSet = buildCommitChangeSet({
      portfolioId: "pf-1",
      tokenRemovals: ["nep141:dai.near"],
    });
    expect(Object.keys(changeSet)).toEqual([
      "portfolio_id",
      "target_changes",
      "token_additions",
      "token_removals",
      "unallocations",
    ]);
  });
});
